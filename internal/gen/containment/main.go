// Command containment writes langtag's region table, regiontable.go, from
// CLDR's supplementalData.xml territoryContainment and the paradigm
// clusters languageInfo.xml's languageMatch rules make of its matchVariable
// entries, each file read at the pin internal/gen/cldr holds.
//
//	go run ./internal/gen/containment    regenerate the table
//
// Run from the module root; go generate does so through regiontable.go.
package main

import (
	"bytes"
	"context"
	"encoding/xml"
	"errors"
	"fmt"
	"go/format"
	"maps"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strconv"
	"strings"

	"github.com/cplieger/langtag/v3/internal/gen/cldr"
	"github.com/cplieger/langtag/v3/internal/gen/subtag"
)

const (
	tableFile = "regiontable.go"
	// matchType is the languageMatches block CLDR's matcher reads, the one
	// whose distance rules use the variables.
	matchType = "written_new"
)

func main() {
	if err := run(context.Background(), ".", cldr.Read); err != nil {
		fmt.Fprintln(os.Stderr, "containment:", err)
		os.Exit(1)
	}
}

// readFunc returns a file at the pin, refusing other bytes; cldr.Read
// outside tests.
type readFunc func(ctx context.Context, f cldr.File) ([]byte, error)

// run writes dir's table from the pinned supplementalData.xml and
// languageInfo.xml.
func run(ctx context.Context, dir string, read readFunc) error {
	supplemental, err := read(ctx, cldr.SupplementalData)
	if err != nil {
		return err
	}
	languageInfo, err := read(ctx, cldr.LanguageInfo)
	if err != nil {
		return err
	}
	table, err := generate(supplemental, languageInfo, cldr.Release)
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, tableFile), table, 0o600)
}

type group struct {
	Type     string `xml:"type,attr"`
	Contains string `xml:"contains,attr"`
}

type supplementalData struct {
	Groups []group `xml:"territoryContainment>group"`
}

type matchVariable struct {
	ID    string `xml:"id,attr"`
	Value string `xml:"value,attr"`
}

type languageMatch struct {
	Desired   string `xml:"desired,attr"`
	Supported string `xml:"supported,attr"`
	Distance  string `xml:"distance,attr"`
	Oneway    string `xml:"oneway,attr"`
}

// matchBlock is one languageMatches element.
type matchBlock struct {
	Type      string          `xml:"type,attr"`
	Variables []matchVariable `xml:"matchVariable"`
	Rules     []languageMatch `xml:"languageMatch"`
}

type languageInfoData struct {
	Matches []matchBlock `xml:"languageMatching>languageMatches"`
}

// generate returns regiontable.go's source for the supplementalData.xml and
// languageInfo.xml of CLDR release, naming both in its header.
func generate(supplemental, languageInfo []byte, release string) ([]byte, error) {
	var doc supplementalData
	if err := xml.Unmarshal(supplemental, &doc); err != nil {
		return nil, fmt.Errorf("parse %s: %w", cldr.SupplementalData.Base(), err)
	}
	table, err := ancestors(doc.Groups)
	if err != nil {
		return nil, err
	}
	block, err := writtenNew(languageInfo)
	if err != nil {
		return nil, err
	}
	variables, err := parseVariables(block.Variables, table)
	if err != nil {
		return nil, err
	}
	clusters, err := evaluateClusters(block.Rules, variables, table)
	if err != nil {
		return nil, err
	}
	pin := cldr.Pin{Release: release}
	var b bytes.Buffer
	b.WriteString("// Code generated by go run ./internal/gen/containment; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "// Source: %s\n", cldr.SupplementalData.URL(pin))
	fmt.Fprintf(&b, "// Source: %s\n", cldr.LanguageInfo.URL(pin))
	fmt.Fprintf(&b, "// CLDR tag: %s\n", release)
	fmt.Fprintf(&b, "// %s SHA-256: %s\n// %s SHA-256: %s\n\n", cldr.SupplementalData.Base(), cldr.SHA256(supplemental), cldr.LanguageInfo.Base(), cldr.SHA256(languageInfo))
	b.WriteString("//go:generate go run ./internal/gen/containment\n\npackage langtag\n\n")
	b.WriteString("// territoryAncestors maps each region CLDR's territoryContainment lists to\n")
	b.WriteString("// every group holding it, directly or through another group. Grouping and\n")
	b.WriteString("// deprecated rows count like any other.\n")
	b.WriteString("var territoryAncestors = map[string][]string{\n")
	for _, r := range slices.Sorted(maps.Keys(table)) {
		fmt.Fprintf(&b, "%q: {%s},\n", r, quoteAll(table[r]))
	}
	b.WriteString("}\n\n")
	b.WriteString("// matchVariables maps each matchVariable of languageInfo.xml's " + matchType + "\n")
	b.WriteString("// languageMatches to the regions it holds, sorted for a binary search: what\n")
	b.WriteString("// its '+' and '-' terms take in, read left to right, a group only when\n")
	b.WriteString("// every region it contains is in. They are the members of the paradigm\n")
	b.WriteString("// clusters regionClusters binds.\n")
	b.WriteString("var matchVariables = map[string][]string{\n")
	for _, id := range slices.Sorted(maps.Keys(variables)) {
		fmt.Fprintf(&b, "%q: {%s},\n", id, quoteAll(variables[id]))
	}
	b.WriteString("}\n\n")
	b.WriteString("// regionClusters binds each matchVariable to the language, and the script\n")
	b.WriteString("// when the rule names one, that the " + matchType + " languageMatch rules bind\n")
	b.WriteString("// it to. No two clusters of one language overlap in script.\n")
	b.WriteString("var regionClusters = []regionCluster{\n")
	for _, c := range clusters {
		script := ""
		if c.script != "" {
			script = fmt.Sprintf("script: %q, ", c.script)
		}
		fmt.Fprintf(&b, "{language: %q, %svariable: %q},\n", c.language, script, c.variable)
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

func quoteAll(codes []string) string {
	q := make([]string, len(codes))
	for i, c := range codes {
		q[i] = strconv.Quote(c)
	}
	return strings.Join(q, ", ")
}

// ancestors returns, for every region a group contains, the sorted groups
// containing it directly or transitively. A group appearing in several rows
// (019 lists its partition and, separately, its groupings) merges them.
func ancestors(groups []group) (map[string][]string, error) {
	parents, err := parentsOf(groups)
	if err != nil {
		return nil, err
	}
	out := make(map[string][]string, len(parents))
	for r := range parents {
		seen := map[string]bool{}
		walk := slices.Clone(parents[r])
		for len(walk) > 0 {
			p := walk[len(walk)-1]
			walk = walk[:len(walk)-1]
			if p == r {
				return nil, fmt.Errorf("territoryContainment puts %s inside itself", r)
			}
			if !seen[p] {
				seen[p] = true
				walk = append(walk, parents[p]...)
			}
		}
		out[r] = slices.Sorted(maps.Keys(seen))
	}
	return out, nil
}

// parentsOf returns each contained region's direct groups, refusing a
// malformed code and an empty group.
func parentsOf(groups []group) (map[string][]string, error) {
	if len(groups) == 0 {
		return nil, fmt.Errorf("%s holds no territoryContainment groups", cldr.SupplementalData.Base())
	}
	parents := map[string][]string{}
	for _, g := range groups {
		if !subtag.Region.MatchString(g.Type) {
			return nil, fmt.Errorf("territoryContainment group %q: malformed region", g.Type)
		}
		members := strings.Fields(g.Contains)
		if len(members) == 0 {
			return nil, fmt.Errorf("territoryContainment group %s contains nothing", g.Type)
		}
		for _, m := range members {
			if !subtag.Region.MatchString(m) {
				return nil, fmt.Errorf("territoryContainment group %s: member %q is malformed", g.Type, m)
			}
			parents[m] = append(parents[m], g.Type)
		}
	}
	return parents, nil
}

// variableID is the id form UTS #35 gives a matchVariable, [$][a-zA-Z0-9]+
// (https://www.unicode.org/reports/tr35/tr35.html#Language_Matching_Variables).
var variableID = regexp.MustCompile(`^\$[A-Za-z0-9]+$`)

// parseVariables returns the regions each of vars holds over ancestors'
// containment, refusing none, a repeated or malformed id and a malformed
// value.
func parseVariables(vars []matchVariable, ancestors map[string][]string) (map[string][]string, error) {
	if len(vars) == 0 {
		return nil, errors.New(cldr.LanguageInfo.Base() + " declares no matchVariable")
	}
	out := make(map[string][]string, len(vars))
	for _, v := range vars {
		if !variableID.MatchString(v.ID) {
			return nil, fmt.Errorf("matchVariable %q: malformed id", v.ID)
		}
		if _, dup := out[v.ID]; dup {
			return nil, fmt.Errorf("matchVariable %s is declared twice", v.ID)
		}
		terms, err := parseValue(v.Value)
		if err != nil {
			return nil, fmt.Errorf("matchVariable %s = %q: %w", v.ID, v.Value, err)
		}
		out[v.ID] = resolve(terms, ancestors)
	}
	return out, nil
}

// term is one region code of a matchVariable value, subtracted when a '-'
// precedes it.
type term struct {
	region   string
	subtract bool
}

// parseValue splits value into its terms. UTS #35 joins region codes with
// '+' for a union and '-' for a set difference, read left to right with no
// precedence.
func parseValue(value string) ([]term, error) {
	var terms []term
	subtract := false
	for {
		code, rest, more := value, "", false
		if i := strings.IndexAny(value, "+-"); i >= 0 {
			code, rest, more = value[:i], value[i+1:], true
		}
		if !subtag.Region.MatchString(code) {
			return nil, fmt.Errorf("term %q, want region codes joined by '+' or '-'", code)
		}
		terms = append(terms, term{region: code, subtract: subtract})
		if !more {
			return terms, nil
		}
		subtract = value[len(code)] == '-'
		value = rest
	}
}

// resolve returns, sorted, the regions terms hold: a region holding no
// other is in when the last term equal to or containing it adds it, and a
// group is in when every such region it contains is. UTS #35 expands a
// macroregion into what it contains. ICU rates a group straddling the set
// at the largest distance of its parts; the tier and the evaluator both
// class it outside.
func resolve(terms []term, ancestors map[string][]string) []string {
	groups := map[string]bool{}
	for _, gs := range ancestors {
		for _, g := range gs {
			groups[g] = true
		}
	}
	universe := placed(ancestors)
	for _, t := range terms {
		if !slices.Contains(universe, t.region) {
			universe = append(universe, t.region)
		}
	}
	slices.Sort(universe)
	leftOut := func(group string) func(string) bool {
		return func(d string) bool { return !groups[d] && within(ancestors, group, d) && !adds(terms, ancestors, d) }
	}
	var out []string
	for _, r := range universe {
		if !slices.ContainsFunc(universe, leftOut(r)) {
			out = append(out, r)
		}
	}
	return out
}

// adds reports whether the last of terms equal to or containing region
// adds it.
func adds(terms []term, ancestors map[string][]string, region string) bool {
	in := false
	for _, t := range terms {
		if within(ancestors, t.region, region) {
			in = !t.subtract
		}
	}
	return in
}

// writtenNew returns src's one matchType languageMatches block.
func writtenNew(src []byte) (matchBlock, error) {
	var doc languageInfoData
	if err := xml.Unmarshal(src, &doc); err != nil {
		return matchBlock{}, fmt.Errorf("parse %s: %w", cldr.LanguageInfo.Base(), err)
	}
	var block matchBlock
	found := 0
	for _, m := range doc.Matches {
		if m.Type == matchType {
			found++
			block = m
		}
	}
	if found != 1 {
		return matchBlock{}, fmt.Errorf("%s holds %d languageMatches of type %s, want 1", cldr.LanguageInfo.Base(), found, matchType)
	}
	return block, nil
}
