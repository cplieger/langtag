// Command pin writes internal/gen/cldr/cldr.go, the one pin every langtag
// table generator reads, fetching each file it pins to record its SHA-256.
//
//	go run ./internal/gen/pin -release <tag> -json <cldr-json release>  move the CLDR pin
//	go run ./internal/gen/pin -iso                                      re-pin the ISO 639-2 file today
//
// Run from the module root, then go generate ./... to regenerate the tables.
package main

import (
	"bytes"
	"context"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"time"

	"github.com/cplieger/langtag/v3/internal/gen/cldr"
)

// pinFile is the file this command writes, relative to the module root.
const pinFile = "internal/gen/cldr/cldr.go"

func main() {
	release := flag.String("release", "", "move the pin to this CLDR release tag")
	jsonVersion := flag.String("json", "", "with -release, the cldr-json release packaging it")
	iso := flag.Bool("iso", false, "fetch the ISO 639-2 file again and pin it at today's date")
	flag.Parse()
	today := time.Now().UTC().Format(time.DateOnly)
	if err := run(context.Background(), ".", request{release: *release, jsonVersion: *jsonVersion, today: today, iso: *iso}, cldr.Get); err != nil {
		fmt.Fprintln(os.Stderr, "pin:", err)
		os.Exit(1)
	}
}

// request is what one run moves: the CLDR pin to release and jsonVersion
// when release is set, and the ISO 639-2 pin to today when iso is.
type request struct {
	release, jsonVersion, today string
	iso                         bool
}

// getFunc returns a file at a pin without checking it; cldr.Get outside
// tests.
type getFunc func(ctx context.Context, f cldr.File, p cldr.Pin) ([]byte, error)

// run writes root's pin file for req, fetching every file whose pin moves.
// It refuses a cldr-json release that does not package the CLDR release, and
// writes nothing when any fetch fails, as when cldr-json lacks the release.
func run(ctx context.Context, root string, req request, get getFunc) error {
	next, err := req.pin()
	if err != nil {
		return err
	}
	fetched := cldr.ISOFetched
	sums := make(map[string]string, len(cldr.Files()))
	for _, f := range cldr.Files() {
		sums[f.Name()] = f.SHA256()
		if (f.Versioned() && req.release == "") || (!f.Versioned() && !req.iso) {
			continue
		}
		b, getErr := get(ctx, f, next)
		if getErr != nil {
			return getErr
		}
		sums[f.Name()] = cldr.SHA256(b)
	}
	if req.iso {
		fetched = req.today
	}
	src, err := render(next, fetched, sums)
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(root, filepath.FromSlash(pinFile)), src, 0o600)
}

// pin returns the CLDR pin req moves to, refusing a request that moves
// nothing or names a cldr-json release without its CLDR release.
func (req request) pin() (cldr.Pin, error) {
	switch {
	case req.release == "" && !req.iso:
		return cldr.Pin{}, errors.New("nothing to move: give -release and -json, or -iso")
	case req.release == "" && req.jsonVersion != "":
		return cldr.Pin{}, errors.New("-json needs -release, the CLDR release it packages")
	case req.release == "":
		return cldr.Pinned(), nil
	}
	if err := checkRelease(req.release, req.jsonVersion); err != nil {
		return cldr.Pin{}, err
	}
	return cldr.Pin{Release: req.release, JSONVersion: req.jsonVersion}, nil
}

// checkRelease refuses a malformed tag and a cldr-json release packaging
// another CLDR release, so the pin never names two.
func checkRelease(release, jsonVersion string) error {
	if err := cldr.CheckTag(release); err != nil {
		return err
	}
	if jsonVersion == "" {
		return errors.New("-release needs -json, the cldr-json release packaging it")
	}
	if err := cldr.CheckTag(jsonVersion); err != nil {
		return err
	}
	packaged, err := cldr.ReleaseOf(jsonVersion)
	if err != nil {
		return err
	}
	if packaged != release {
		return fmt.Errorf("cldr-json %s packages CLDR %s, not %s", jsonVersion, packaged, release)
	}
	return nil
}

// render returns cldr.go's source for p, the ISO 639-2 file's fetch date and
// sums, the SHA-256 of each cldr.Files entry by name.
func render(p cldr.Pin, isoFetched string, sums map[string]string) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by go run ./internal/gen/pin; DO NOT EDIT.\n\npackage cldr\n\n")
	b.WriteString("// The CLDR release every table reads, the cldr-json release packaging it,\n")
	b.WriteString("// and the day the unversioned ISO 639-2 file was fetched.\n")
	fmt.Fprintf(&b, "const (\n\tRelease = %q\n\tJSONVersion = %q\n\tISOFetched = %q\n)\n\n", p.Release, p.JSONVersion, isoFetched)
	b.WriteString("// sums holds the SHA-256 of each File by name.\n")
	b.WriteString("var sums = map[string]string{\n")
	for _, f := range cldr.Files() {
		fmt.Fprintf(&b, "\t%q: %q,\n", f.Name(), sums[f.Name()])
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}
