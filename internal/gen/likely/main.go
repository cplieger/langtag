// Command likely writes langtag's script table, scripttable.go, from CLDR's
// likelySubtags.xml at the pin internal/gen/cldr holds.
//
//	go run ./internal/gen/likely              regenerate the table
//	go run ./internal/gen/likely -diff <tag>  report on stdout how CLDR <tag> changes it
//
// Run from the module root; go generate does so through scripttable.go.
package main

import (
	"bytes"
	"context"
	"encoding/xml"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"io"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/cplieger/langtag/v3/internal/gen/cldr"
	"github.com/cplieger/langtag/v3/internal/gen/subtag"
)

const tableFile = "scripttable.go"

func main() {
	diff := flag.String("diff", "", "write a Markdown report of how this CLDR release tag changes the table to stdout, and no file")
	flag.Parse()
	var err error
	if *diff != "" {
		err = report(context.Background(), os.Stdout, *diff, cldr.Read, cldr.Get)
	} else {
		err = run(context.Background(), ".", cldr.Read)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "likely:", err)
		os.Exit(1)
	}
}

// readFunc returns a file at the pin, refusing other bytes; cldr.Read
// outside tests.
type readFunc func(ctx context.Context, f cldr.File) ([]byte, error)

// getFunc returns a file at another pin, unchecked; cldr.Get outside tests.
type getFunc func(ctx context.Context, f cldr.File, p cldr.Pin) ([]byte, error)

// run writes dir's table from the pinned likelySubtags.xml.
func run(ctx context.Context, dir string, read readFunc) error {
	src, err := read(ctx, cldr.LikelySubtags)
	if err != nil {
		return err
	}
	table, err := generate(src, cldr.Release)
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, tableFile), table, 0o600)
}

// report writes to w writeDiff's report of the table moving from the pinned
// likelySubtags.xml to release tag's, writing no file: the refresh runs it
// before it moves the pin.
func report(ctx context.Context, w io.Writer, tag string, read readFunc, get getFunc) error {
	if err := cldr.CheckTag(tag); err != nil {
		return err
	}
	old, err := read(ctx, cldr.LikelySubtags)
	if err != nil {
		return err
	}
	next, err := get(ctx, cldr.LikelySubtags, cldr.Pin{Release: tag})
	if err != nil {
		return err
	}
	return reportChange(w, old, next)
}

// reportChange writes writeDiff's report of the rows of next, a
// likelySubtags.xml, against those of old.
func reportChange(w io.Writer, old, next []byte) error {
	before, err := parseRows(old)
	if err != nil {
		return err
	}
	after, err := parseRows(next)
	if err != nil {
		return err
	}
	return writeDiff(w, before, after)
}

type likelySubtag struct {
	From string `xml:"from,attr"`
	To   string `xml:"to,attr"`
}

type supplementalData struct {
	Rows []likelySubtag `xml:"likelySubtags>likelySubtag"`
}

type row struct{ language, region, script string }

// generate returns scripttable.go's source for src, the likelySubtags.xml
// of CLDR release, naming both in its header.
func generate(src []byte, release string) ([]byte, error) {
	rows, err := parseRows(src)
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by go run ./internal/gen/likely; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "// Source: %s\n", cldr.LikelySubtags.URL(cldr.Pin{Release: release}))
	fmt.Fprintf(&b, "// CLDR tag: %s\n// SHA-256: %s\n\n", release, cldr.SHA256(src))
	b.WriteString("//go:generate go run ./internal/gen/likely\n\npackage langtag\n\n")
	// One constant per script keeps each literal in one place, which the
	// hand-written tables then name (scriptLatn) instead of repeating.
	b.WriteString("const (\n")
	for _, sc := range scripts(rows) {
		fmt.Fprintf(&b, "script%s = %q\n", sc, sc)
	}
	b.WriteString(")\n\nvar languageScripts = []languageScript{\n")
	for _, r := range rows {
		if r.region == "" {
			fmt.Fprintf(&b, "{%q, script%s},\n", r.language, r.script)
		}
	}
	b.WriteString("}\n\nvar regionScripts = []regionScript{\n")
	for _, r := range rows {
		if r.region != "" {
			fmt.Fprintf(&b, "{%q, %q, script%s},\n", r.language, r.region, r.script)
		}
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

// scripts returns the distinct scripts of rows, sorted.
func scripts(rows []row) []string {
	out := make([]string, 0, len(rows))
	for _, r := range rows {
		out = append(out, r.script)
	}
	slices.Sort(out)
	return slices.Compact(out)
}

// parseRows returns the language and language-region rows of src, sorted by
// language then region. The und rows and the language-script rows are
// dropped: a resolved script is needed only when the tag states none.
func parseRows(src []byte) ([]row, error) {
	var doc supplementalData
	if err := xml.Unmarshal(src, &doc); err != nil {
		return nil, fmt.Errorf("parse likelySubtags.xml: %w", err)
	}
	var rows []row
	for _, ls := range doc.Rows {
		r, keep, err := parseRow(ls)
		if err != nil {
			return nil, err
		}
		if keep {
			rows = append(rows, r)
		}
	}
	if len(rows) == 0 {
		return nil, errors.New("likelySubtags.xml holds no language rows")
	}
	slices.SortFunc(rows, func(a, b row) int {
		if c := strings.Compare(a.language, b.language); c != 0 {
			return c
		}
		return strings.Compare(a.region, b.region)
	})
	for i := 1; i < len(rows); i++ {
		if rows[i].language == rows[i-1].language && rows[i].region == rows[i-1].region {
			return nil, fmt.Errorf("likelySubtags.xml repeats the row %s_%s", rows[i].language, rows[i].region)
		}
	}
	return rows, nil
}

func parseRow(ls likelySubtag) (r row, keep bool, err error) {
	from := strings.Split(ls.From, "_")
	to := strings.Split(ls.To, "_")
	if from[0] == "und" {
		return row{}, false, nil
	}
	if len(to) != 3 || !subtag.Script.MatchString(to[1]) {
		return row{}, false, fmt.Errorf("likelySubtag %s -> %s: want <language>_<Script>_<REGION>", ls.From, ls.To)
	}
	if !subtag.Language.MatchString(from[0]) {
		return row{}, false, fmt.Errorf("likelySubtag %s: malformed language subtag", ls.From)
	}
	switch {
	case len(from) == 1:
		return row{language: from[0], script: to[1]}, true, nil
	case len(from) == 2 && subtag.Script.MatchString(from[1]):
		return row{}, false, nil
	case len(from) == 2 && subtag.Region.MatchString(from[1]):
		return row{language: from[0], region: from[1], script: to[1]}, true, nil
	default:
		return row{}, false, fmt.Errorf("likelySubtag %s: want <language>, <language>_<Script> or <language>_<REGION>", ls.From)
	}
}
